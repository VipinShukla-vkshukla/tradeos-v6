-- SWAP EXECUTIONS — audit trail for swing swap execution results.
--
-- The swap execution engine (backend/swing/compute/swap_execution.py) already
-- writes one audit row per executed/blocked swap to a `swap_executions` table,
-- but no migration ever created it — see that module's own warning, "table may
-- need migration". Until this table exists every auto-swap is blocked at the
-- circuit-breaker read (_daily_swap_count swallows the missing-table error and
-- returns 0) and its audit row is silently dropped. This creates the table.
--
-- SWING ONLY. Nothing here reads or writes intraday positions.
--
-- ADDS swapped_at column to open_positions for audit trail of swap exits.
ALTER TABLE public.open_positions
    ADD COLUMN IF NOT EXISTS swapped_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS public.swap_executions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sell_symbol   text,
    buy_symbol    text,
    sell_rank     numeric,
    buy_rank      numeric,
    margin        numeric,
    regime        text,
    status        text,          -- EXECUTED | PARTIAL | BLOCKED | SKIPPED
    sell_order_id text,
    buy_order_id  text,
    blocked_reason text,
    executed_at   timestamptz DEFAULT now(),
    created_at    timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_swap_exec_date
    ON public.swap_executions (executed_at DESC);

